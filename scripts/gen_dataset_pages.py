#!/usr/bin/env python3
"""Generate one reproducible public page per manifest dataset."""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts.public_surface_generation import (
    GenerationError,
    load_json,
    load_public_surfaces,
    publish_text_outputs,
)

STATUSES = frozenset({"fresh", "aging", "stale", "discontinued", "degraded", "browser-dependent", "unreachable", "unknown", "unknown-freshness", "reference"})
ID_RE = re.compile(r"[A-Za-z0-9][A-Za-z0-9_-]*\Z")


def _rows(document: dict[str, Any], key: str, source: str) -> list[dict[str, Any]]:
    rows = document.get(key)
    if not isinstance(rows, list) or not all(isinstance(row, dict) for row in rows):
        raise GenerationError(f"{source}: {key} must be an array of objects")
    return rows


def _value(value: object, absent: str = "Not published") -> str:
    return html.escape(str(value) if value is not None and value != "" else absent, quote=True)


def _field(label: str, value: object, source: str, absent: str = "Not published") -> str:
    return f'<dt>{html.escape(label)}</dt><dd>{_value(value, absent)} <small>({source})</small></dd>'


def render_page(dataset: dict[str, Any], health: dict[str, Any] | None, origin: str, path_template: str, observed_at: str) -> str:
    """Render source-attributed facts for one dataset."""
    dataset_id = dataset["id"]
    name = dataset.get("name")
    status = health.get("status") if health is not None else "unknown"
    if status not in STATUSES:
        raise GenerationError(f"{dataset_id}: invalid published status {status!r}")
    canonical = f"{origin}{path_template.format(id=dataset_id)}"
    jsonld_url = f"{origin}/data/jsonld/{dataset_id}.json"
    title = f"Is {_value(name)} ({_value(dataset_id)}) still updated?"
    source = "health/latest.json" if health is not None else "health/latest.json: no row for this dataset"
    current = health or {}
    fields = [
        _field("Dataset ID", dataset_id, "datapulse.json"),
        _field("Name", name, "datapulse.json"),
        _field("Published status", status, source),
        _field("Content freshness date", current.get("content_freshness_date"), source, "No content date was published"),
        _field("Freshness signal source", current.get("freshness_signal_source"), source),
        _field("Last checked", current.get("last_checked"), source),
        _field("Record count", current.get("record_count"), source),
        _field("Licence", dataset.get("licence"), "datapulse.json"),
        _field("Attribution", dataset.get("attribution"), "datapulse.json"),
        _field("Steward", dataset.get("steward"), "datapulse.json"),
        _field("Custodian", dataset.get("custodian"), "datapulse.json"),
        _field("Upstream source URL", dataset.get("url"), "datapulse.json"),
        _field("Canonical URL", canonical, "config/public-surfaces.json + datapulse.json"),
        _field("Observation time", observed_at, "health/latest.json"),
    ]
    structured = {
        "@context": "https://schema.org", "@type": "Dataset", "identifier": dataset_id,
        "name": name, "url": canonical, "sameAs": dataset.get("url"),
        "license": dataset.get("licence"), "dateModified": current.get("content_freshness_date"),
        "additionalProperty": [
            {"@type": "PropertyValue", "name": "published status", "value": status},
            {"@type": "PropertyValue", "name": "freshness signal source", "value": current.get("freshness_signal_source")},
            {"@type": "PropertyValue", "name": "last checked", "value": current.get("last_checked")},
            {"@type": "PropertyValue", "name": "record count", "value": current.get("record_count")},
            {"@type": "PropertyValue", "name": "attribution", "value": dataset.get("attribution")},
            {"@type": "PropertyValue", "name": "steward", "value": dataset.get("steward")},
            {"@type": "PropertyValue", "name": "custodian", "value": dataset.get("custodian")},
            {"@type": "PropertyValue", "name": "observation time", "value": observed_at},
        ],
    }
    jsonld = json.dumps(structured, ensure_ascii=False, sort_keys=True).replace("<", "\\u003c")
    field_block = "\n".join(fields)
    return (
        "<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n"
        f"<title>{title}</title>\n<link rel=\"canonical\" href=\"{_value(canonical)}\">\n"
        f"<script type=\"application/ld+json\">{jsonld}</script>\n</head>\n<body>\n"
        "<!-- Generated by scripts/gen_dataset_pages.py; edit the inputs, then regenerate. -->\n"
        f"<h1>{title}</h1>\n"
        + ("<p>health/latest.json snapshot has no row for this dataset.</p>\n" if health is None else "")
        + f"<dl>\n{field_block}\n</dl>\n"
        f'<p><a href="{_value(jsonld_url)}">Dataset JSON-LD (data/jsonld/{_value(dataset_id)}.json)</a></p>\n'
        "</body>\n</html>\n"
    )


def expected_outputs(root: Path) -> dict[Path, str]:
    """Join manifest and snapshot without inventing missing health facts."""
    config = load_public_surfaces(root)
    manifest = _rows(load_json(root / "datapulse.json"), "datasets", "datapulse.json")
    snapshot = load_json(root / "health/latest.json")
    health_rows = _rows(snapshot, "datasets", "health/latest.json")
    observed_at = snapshot.get("checked_at")
    if not isinstance(observed_at, str) or not observed_at:
        raise GenerationError("health/latest.json: checked_at must be a non-empty string")
    health_by_id: dict[str, dict[str, Any]] = {}
    for row in health_rows:
        key = row.get("dataset_id")
        if not isinstance(key, str) or key in health_by_id:
            raise GenerationError(f"health/latest.json: invalid or duplicate dataset_id {key!r}")
        health_by_id[key] = row
    outputs: dict[Path, str] = {}
    for dataset in sorted(manifest, key=lambda row: str(row.get("id", ""))):
        dataset_id = dataset.get("id")
        if not isinstance(dataset_id, str) or not ID_RE.fullmatch(dataset_id):
            raise GenerationError(f"datapulse.json: unsafe dataset id {dataset_id!r}")
        target = root / "docs/datasets" / f"{dataset_id}.html"
        if target in outputs:
            raise GenerationError(f"datapulse.json: duplicate dataset id {dataset_id!r}")
        outputs[target] = render_page(dataset, health_by_id.get(dataset_id), config["origins"]["website"], config["dataset_pages"]["path_template"], observed_at)
    return outputs


def generate(root: Path, *, check: bool = False) -> int:
    """Write or compare the complete page family; return its page count."""
    outputs = expected_outputs(root)
    if check:
        for path, content in outputs.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                print(f"stale: {path}", file=sys.stderr)
        if publish_text_outputs(outputs, check=True):
            raise GenerationError("dataset pages are stale")
    else:
        publish_text_outputs(outputs)
    return len(outputs)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        count = generate(args.root, check=args.check)
    except GenerationError as error:
        print(f"gen_dataset_pages.py: {error}", file=sys.stderr)
        return 1
    print(f"gen_dataset_pages.py: {count} pages")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
