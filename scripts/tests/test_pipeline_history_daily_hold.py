#!/usr/bin/env python3
from __future__ import annotations

import json
import os
from pathlib import Path
import subprocess

import pytest

PIPELINE = Path(__file__).resolve().parents[1] / "datapulse-pipeline.sh"
PATH_IN_REPO = "health/history_daily.json"


def history(*dates: str, marker: str = "") -> str:
    return json.dumps({"aggregates": [{"dataset_id": marker, "date": date} for date in dates]})


def run_staging(tmp_path: Path, committed: str | None, working: str) -> tuple[list[str], str]:
    repo = tmp_path / "repo"
    repo.mkdir()
    env = {**os.environ, "GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": "/dev/null"}

    def git(*args: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(["git", "-C", str(repo), *args], env=env, text=True, capture_output=True, check=True)

    git("init", "-q")
    git("config", "user.name", "History test")
    git("config", "user.email", "history@example.invalid")
    (repo / "health").mkdir()
    (repo / "anchor").write_text("initial")
    if committed is not None:
        (repo / PATH_IN_REPO).write_text(committed)
    git("add", ".")
    git("commit", "-qm", "initial")
    (repo / PATH_IN_REPO).write_text(working)
    # Run the actual publish-stage commands, bracketed by their existing neighbors.
    source = PIPELINE.read_text()
    start = source.index("  swap_artifacts\n", source.index("STAGE_GAP_TIMING publish.swap start")) + len("  swap_artifacts\n")
    end = source.index('\n\n  if git_repo diff --cached', start)
    staging = source[start:end]
    subprocess.run(
        ["bash", "-c", 'source "$1"; repo="$2"; publish_artifact_paths=(health)\n' + staging, "bash", str(PIPELINE), str(repo)],
        env=env, text=True, capture_output=True, check=True,
    )
    git("commit", "-qm", "cycle", "--allow-empty")
    return git("diff-tree", "--no-commit-id", "--name-only", "-r", "HEAD").stdout.splitlines(), (repo / PATH_IN_REPO).read_text()


def test_newer_day_is_committed(tmp_path: Path) -> None:
    working = history("2026-11-14", "2026-11-12", marker="new")
    changed, actual = run_staging(tmp_path, history("2026-11-13", "2026-11-11"), working)
    assert (changed, actual) == ([PATH_IN_REPO], working), "advanced newest day must commit the generated bytes"


def test_same_newest_day_is_held(tmp_path: Path) -> None:
    committed = history("2026-11-12", "2026-11-13", marker="old")
    changed, actual = run_staging(tmp_path, committed, history("2026-11-13", "2026-11-11", marker="new"))
    assert (changed, actual) == ([], committed), "unchanged newest day must restore HEAD and stay out of the commit"


def test_no_committed_copy_is_committed(tmp_path: Path) -> None:
    working = history("2026-11-13")
    changed, actual = run_staging(tmp_path, None, working)
    assert (changed, actual) == ([PATH_IN_REPO], working), "first daily history must be committed"


def test_older_day_is_held(tmp_path: Path) -> None:
    committed = history("2026-11-13")
    changed, actual = run_staging(tmp_path, committed, history("2026-11-12"))
    assert (changed, actual) == ([], committed), "an older newest day must not replace HEAD"


def test_invalid_dates_do_not_mask_an_advance(tmp_path: Path) -> None:
    working = history("2026-11-14", "9999-99-99-extra")
    changed, actual = run_staging(tmp_path, history("2026-11-13", "9999-99-99-extra"), working)
    assert (changed, actual) == ([PATH_IN_REPO], working), "invalid date shapes must not mask a valid advance"


def test_malformed_committed_copy_does_not_block_publication(tmp_path: Path) -> None:
    working = history("2026-11-14")
    changed, actual = run_staging(tmp_path, "{broken", working)
    assert (changed, actual) == ([PATH_IN_REPO], working), "malformed HEAD must not block the working copy"


@pytest.mark.parametrize("working", ["", "{broken"])
def test_invalid_working_copy_does_not_replace_good_head(tmp_path: Path, working: str) -> None:
    committed = history("2026-11-13")
    changed, actual = run_staging(tmp_path, committed, working)
    assert (changed, actual) == ([], committed), "invalid daily history must not replace a good committed copy"
